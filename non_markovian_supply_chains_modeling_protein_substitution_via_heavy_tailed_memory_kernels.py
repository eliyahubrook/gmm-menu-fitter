import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from datetime import timedelta

# --- 1. Simulation Parameters & Historical Slice ---
forecast_days = 60
n_paths = 100  # Number of Monte Carlo trajectories
hist_days = 90
window = fitter.window

last_date = df_scraped['date'].max()
hist_start = last_date - timedelta(days=hist_days)
hist_df = df_scraped[df_scraped['date'] >= hist_start].copy()

# Extract historical drift and volatility for Brent (BZ=F)
returns_brent_hist = df_scraped['brent_returns'].replace([np.inf, -np.inf], np.nan).dropna()
mu_brent = returns_brent_hist.mean()
sigma_brent = returns_brent_hist.std()
last_norm_brent_price = df_scraped['brent_normalized'].iloc[-1]
seed_brent_prices = df_scraped['brent_normalized'].iloc[-window:].values
seed_brent_returns = df_scraped['brent_returns'].iloc[-window:].values

# Extract historical drift and volatility for Beef (LE=F)
returns_beef_hist = df_scraped['beef_returns'].replace([np.inf, -np.inf], np.nan).dropna()
mu_beef = returns_beef_hist.mean()
sigma_beef = returns_beef_hist.std()
last_norm_beef_price = df_scraped['beef_normalized'].iloc[-1]
seed_beef_prices = df_scraped['beef_normalized'].iloc[-window:].values
seed_beef_returns = df_scraped['beef_returns'].iloc[-window:].values

# --- 2. Monte Carlo Execution Setup ---
future_dates = [last_date + timedelta(days=i) for i in range(1, forecast_days + 1)]

# Generate independent random normal shocks for Brent and Beef for each path and day
np.random.seed(42)
Z_brent = np.random.normal(0, 1, (forecast_days, n_paths))
Z_beef = np.random.normal(0, 1, (forecast_days, n_paths))

# Initialize simulation arrays
sim_brent_prices = np.zeros((forecast_days, n_paths))
sim_brent_returns = np.zeros((forecast_days, n_paths))
sim_beef_prices = np.zeros((forecast_days, n_paths))
sim_beef_returns = np.zeros((forecast_days, n_paths))
sim_hazard = np.zeros((forecast_days, n_paths))
sim_p_red = np.zeros((forecast_days, n_paths))

# Define the sensitivity of beef price drift to red meat substitution probability
price_sensitivity_to_p_red = 0.002

# (Optional but recommended) Clip adjusted_mu_beef so it cannot run away
# This line had a syntax error; np.clip arguments should be in parentheses.
# The clipping was intended to happen during the simulation loop after `adjusted_mu_beef` is calculated.
# Removed from here and will be applied within the loop.

# --- 3. Propagate the Non-Markovian Memory Kernels and Simulate with Feedback ---
for path in range(n_paths):
    # Initialize full history for memory calculation for this path
    # These lists will be dynamically updated with simulated values
    current_full_brent_prices = list(seed_brent_prices - 1.0) # Subtract 1.0 for stress_memory calculation
    current_full_brent_returns = list(seed_brent_returns)
    current_full_beef_prices = list(seed_beef_prices - 1.0) # Subtract 1.0 for stress_memory calculation
    current_full_beef_returns = list(seed_beef_returns)

    # Initialize first day of simulation for both Brent and Beef
    sim_brent_prices[0, path] = last_norm_brent_price * np.exp((mu_brent - 0.5 * sigma_brent**2) + sigma_brent * Z_brent[0, path])
    sim_brent_returns[0, path] = sim_brent_prices[0, path] / last_norm_brent_price - 1.0

    sim_beef_prices[0, path] = last_norm_beef_price * np.exp((mu_beef - 0.5 * sigma_beef**2) + sigma_beef * Z_beef[0, path])
    sim_beef_returns[0, path] = sim_beef_prices[0, path] / last_norm_beef_price - 1.0

    # Append first simulated day's values to history for subsequent memory calculations
    current_full_brent_prices.append(sim_brent_prices[0, path] - 1.0)
    current_full_brent_returns.append(sim_brent_returns[0, path])
    current_full_beef_prices.append(sim_beef_prices[0, path] - 1.0)
    current_full_beef_returns.append(sim_beef_returns[0, path])


    for t in range(forecast_days):
        # Take the last 'window' days for memory calculation
        past_brent_ret_window = np.array(current_full_brent_returns[-window:])
        past_brent_price_window = np.array(current_full_brent_prices[-window:])
        past_beef_price_window = np.array(current_full_beef_prices[-window:])

        # Calculate memory terms
        v_mem = np.sum(np.abs(past_brent_ret_window[::-1]) * fitter.kernel)
        s_mem_brent = np.sum(past_brent_price_window[::-1] * fitter.kernel)
        s_mem_beef = np.sum(past_beef_price_window[::-1] * fitter.kernel)

        # Apply GMM parameters to calculate hazard and P(Red) for *current* time `t`
        sim_hazard[t, path] = results['lambda_0'] * results['gamma'] * v_mem
        # Adjusted logit includes both Brent and Beef stress memories
        adj_logit = results['logit_base_red'] - (results['beta'] * s_mem_brent) - (results['beta_beef'] * s_mem_beef)
        sim_p_red[t, path] = 1.0 / (1.0 + np.exp(-adj_logit))

        if t < forecast_days - 1: # Only simulate if not the last day
            # 1. Simulate next price step for Brent (standard GBM)
            sim_brent_prices[t+1, path] = sim_brent_prices[t, path] * np.exp((mu_brent - 0.5 * sigma_brent**2) + sigma_brent * Z_brent[t+1, path])
            sim_brent_returns[t+1, path] = sim_brent_prices[t+1, path] / sim_brent_prices[t, path] - 1.0

            # 2. Simulate next price step for Beef with feedback from P(Red) from current `t`
            p_red_deviation = sim_p_red[t, path] - (1/3) # Deviation from baseline P(Red)
            # Apply clipping here, after adjusted_mu_beef is calculated
            adjusted_mu_beef = np.clip(mu_beef + price_sensitivity_to_p_red * p_red_deviation, -0.01, 0.01)

            sim_beef_prices[t+1, path] = sim_beef_prices[t, path] * np.exp((adjusted_mu_beef - 0.5 * sigma_beef**2) + sigma_beef * Z_beef[t+1, path])
            sim_beef_returns[t+1, path] = sim_beef_prices[t+1, path] / sim_beef_prices[t, path] - 1.0

            # Append the newly simulated prices and returns for next iteration's memory calculation
            current_full_brent_prices.append(sim_brent_prices[t+1, path] - 1.0)
            current_full_brent_returns.append(sim_brent_returns[t+1, path])
            current_full_beef_prices.append(sim_beef_prices[t+1, path] - 1.0)
            current_full_beef_returns.append(sim_beef_returns[t+1, path])


# --- 4. Plotting the Dashboard ---
# Calculate 5th, 50th (median), and 95th percentiles for the fan charts
pct_brent_price = np.percentile(sim_brent_prices, [5, 50, 95], axis=1)
pct_beef_price = np.percentile(sim_beef_prices, [5, 50, 95], axis=1) # New: Beef prices
pct_hazard = np.percentile(sim_hazard, [5, 50, 95], axis=1)
pct_pred = np.percentile(sim_p_red, [5, 50, 95], axis=1)

# Recalculate historical values for the plot (now also for Beef)
hist_hazard = results['lambda_0'] * results['gamma'] * hist_df['vol_memory']
