import numpy as np
from scipy.optimize import minimize

class GMMMenuFitter:
    def __init__(self, data, window, alpha_fixed):
        self.data = data
        self.window = window
        self.alpha_fixed = alpha_fixed
        self.N = len(data) - window

        # Replace the exponential kernel with a heavy-tailed power-law kernel
        lags = np.arange(1, self.window + 1)
        self.kernel = (1 + lags) ** (-self.alpha_fixed)

    def moment_conditions(self, theta: np.ndarray) -> np.ndarray:
        """
        theta = [lambda_0, gamma, beta, logit_base_red, beta_beef]
        Returns an N x 5 matrix of moment conditions g_i(theta).
        """
        lam_0, gamma, beta, logit_base, beta_beef = theta

        # Restrict parameters to valid theoretical domains
        lam_0 = np.clip(lam_0, 0.001, 0.999)
        gamma = np.clip(gamma, 0.0, 50.0)
        beta = np.clip(beta, -5.0, 5.0)
        beta_beef = np.clip(beta_beef, -5.0, 5.0)

        g = np.zeros((self.N, 5)) # Changed to 5 columns

        for idx, i in enumerate(range(self.window, len(self.data))):
            row = self.data.iloc[i]

            # 1. Hazard Decomposition
            base_hazard = 1.0 if row['is_wednesday'] else lam_0
            delta_hazard = base_hazard * gamma * row['vol_memory']

            # Total unclipped hazard for accurate proportional weighting
            total_raw_hazard = base_hazard + delta_hazard
            effective_hazard = np.clip(total_raw_hazard, 0, 1)

            # Moment 1: Overall transition rate matching
            hazard_residual = row['menu_changed_observed'] - effective_hazard
            g[idx, 0] = hazard_residual

            # Moment 2: Volatility sensitivity matching (Brent)
            g[idx, 1] = hazard_residual * row['vol_memory']

            # 2. State Substitution Mixture Model (Evaluated only on change events)
            if row['menu_changed_observed']:
                # Attribution weights
                w_base = base_hazard / total_raw_hazard
                w_shock = delta_hazard / total_raw_hazard

                # Shock-induced substitution probability
                adjusted_logit = logit_base - (beta * row['stress_memory']) - (beta_beef * row['beef_stress_memory']) # Updated to include beef_stress_memory
                p_red_shock = 1.0 / (1.0 + np.exp(-adjusted_logit))

                # Mixture probability: Baseline noise does not alter protein type
                p_red_base = 1.0 / 3.0
                mixture_prob_red = (w_base * p_red_base) + (w_shock * p_red_shock)

                state_residual = row['is_red_observed'] - mixture_prob_red

                # Moment 3: Baseline state matching
                g[idx, 2] = state_residual
                # Moment 4: Price stress sensitivity (weighted by shock isolation) (Brent)
                g[idx, 3] = state_residual * row['stress_memory']
                # Moment 5: Price stress sensitivity (weighted by shock isolation) (Beef) # New moment
                g[idx, 4] = state_residual * row['beef_stress_memory']
            else:
                g[idx, 2] = 0.0
                g[idx, 3] = 0.0
                g[idx, 4] = 0.0

        return g

    def gmm_objective(self, theta, W):
        g = self.moment_conditions(theta)
        # The GMM objective is J = mean(g).T @ W @ mean(g)
        g_mean = np.mean(g, axis=0)
        return g_mean.T @ W @ g_mean

    def fit(self):
        # Initial guess: [lam_0, gamma, beta, logit_base_red, beta_beef]
        theta_init = np.array([0.01, 2.0, 1.0, -0.693, 0.5]) # Added initial guess for beta_beef

        # Define bounds for parameters: [lam_0, gamma, beta, logit_base_red, beta_beef]
        bounds = [
            (0.001, 0.999),  # lam_0: (0, 1)
            (0.0, 50.0),     # gamma: (0, inf)
            (-5.0, 5.0),     # beta: (-inf, inf)
            (-5.0, 5.0),     # logit_base_red: (-inf, inf)
            (-5.0, 5.0)      # beta_beef: (-inf, inf)
        ]

        # Step 1: Minimize using an Identity Weighting Matrix
        W_identity = np.eye(5) # Changed to 5x5
        print("Running Step 1 GMM (Identity Matrix)...")
        # Changed method to 'L-BFGS-B' to support bounds
        res_step1 = minimize(self.gmm_objective, theta_init, args=(W_identity,), method='L-BFGS-B', bounds=bounds)
        theta_step1 = res_step1.x

        # Compute Optimal Weighting Matrix from Step 1 residuals
        g_matrix_step1 = self.moment_conditions(theta_step1)
        g_cov = np.cov(g_matrix_step1, rowvar=False)
        W_optimal = np.linalg.inv(g_cov + np.eye(5) * 1e-6) # Changed to 5x5

        # Step 2: Minimize using Optimal Inverse-Covariance Weighting
        print("Running Step 2 GMM (Optimal Covariance Weighting)...")
        # Changed method to 'L-BFGS-B' to support bounds
        res_step2 = minimize(self.gmm_objective, theta_step1, args=(W_optimal,), method='L-BFGS-B', bounds=bounds)
        theta_step2 = res_step2.x

        return {
            'lambda_0': theta_step2[0],
            'gamma': theta_step2[1],
            'beta': theta_step2[2],
            'logit_base_red': theta_step2[3],
            'beta_beef': theta_step2[4], # New parameter
            'objective_value': res_step2.fun # Changed to actual objective value
        }

