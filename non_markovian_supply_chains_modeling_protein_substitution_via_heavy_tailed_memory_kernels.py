import yfinance as yf
import pandas as pd
import numpy as np

# 1. Fetch live Brent Crude baseline
print("Pulling BZ=F futures...")
brent = yf.download("BZ=F", start="2025-08-01", end="2026-10-01", progress=False)
brent = brent.reindex(pd.date_range(start="2025-08-01", end=brent.index[-1], freq='D')).ffill()
print("Pulling LE=F futures...")
beef = yf.download("LE=F", start="2025-08-01", end="2026-10-01", progress=False)
beef = beef.reindex(pd.date_range(start="2025-08-01", end=beef.index[-1], freq='D')).ffill()

# Ensure both dataframes have the same index for consistent merging
common_index = brent.index.intersection(beef.index)
brent = brent.loc[common_index]
beef = beef.loc[common_index]


# 2. Construct the synthetic operational log
np.random.seed(42)
df_scraped = pd.DataFrame({
    'date': brent.index,
    'is_wednesday': brent.index.weekday == 2,
    # Standardize inputs to prevent gradient explosion
    'brent_returns': brent['Close'].pct_change().fillna(0).values.flatten(),
    'brent_normalized': (brent['Close'] / brent['Close'].iloc[0]).values.flatten(),
    'beef_returns': beef['Close'].pct_change().fillna(0).values.flatten(),
    'beef_normalized': (beef['Close'] / beef['Close'].iloc[0]).values.flatten()
})

# Define window and alpha_fixed for memory calculations
window_val = 30
alpha_fixed_val = 0.8
kernel = (1 + np.arange(1, window_val + 1)) ** (-alpha_fixed_val)

# Calculate vol_memory and stress_memory
df_scraped['vol_memory'] = np.nan
df_scraped['stress_memory'] = np.nan
df_scraped['beef_stress_memory'] = np.nan # New: Beef stress memory

for i in range(window_val, len(df_scraped)):
    # Slice historical returns/prices for the current window
    past_returns_slice = df_scraped['brent_returns'].iloc[i - window_val : i].values
    past_prices_slice = (df_scraped['brent_normalized'].iloc[i - window_val : i] - 1.0).values
    past_beef_prices_slice = (df_scraped['beef_normalized'].iloc[i - window_val : i] - 1.0).values # New: Beef prices slice


    # Calculate memory terms by convolving with the kernel
    df_scraped.loc[i, 'vol_memory'] = np.sum(np.abs(past_returns_slice)[::-1] * kernel)
    df_scraped.loc[i, 'stress_memory'] = np.sum(past_prices_slice[::-1] * kernel)
    df_scraped.loc[i, 'beef_stress_memory'] = np.sum(past_beef_prices_slice[::-1] * kernel) # New: Calculate beef stress memory


# 3. Simulate observed menu states (Injecting the competing risks)
# Baseline 2% daily change chance, forced 100% on Wednesdays
true_hazard = 0.02 + 5.0 * df_scraped['vol_memory'].fillna(0)
df_scraped['menu_changed_observed'] = np.random.rand(len(df_scraped)) < np.clip(true_hazard, 0, 1)
df_scraped.loc[df_scraped['is_wednesday'], 'menu_changed_observed'] = True
# When changed, roughly 33% chance of red meat
df_scraped['is_red_observed'] = np.where(df_scraped['menu_changed_observed'],
                                         (np.random.rand(len(df_scraped)) < 0.33).astype(float),
                                         0.0)

# 4. Execute the Two-Step GMM
fitter = GMMMenuFitter(df_scraped, window=window_val, alpha_fixed=alpha_fixed_val)
results = fitter.fit()
print("\n--- GMM Optimization Results ---")
for key, val in results.items():
    print(f"{key}: {val}")

